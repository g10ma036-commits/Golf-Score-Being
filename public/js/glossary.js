// 数字の名前に「?」を付けて、押すと説明を開くボタンにする
export function termLabel(label, key) {
  if (!TERMS[key]) return label;
  return html`<button type="button" class="term" data-term="${key}" aria-label="${label}（説明を見る）">${label}<span class="term-i" aria-hidden="true">?</span></button>`;
}

export function termBody(key) {
  const [, text, how, guide] = TERMS[key];
  return html`<p>${text}</p>
    ${how ? html`<p class="small secondary" style="margin-top:8px"><strong>このアプリでの数え方</strong>：${how}</p>` : ''}
    ${guide ? html`<table class="data term-guide"><caption class="small muted">目安</caption><tbody>${guide.map(([who, v]) => html`<tr><td>${who}</td><td class="r">${v}</td></tr>`)}</tbody></table>
      <p class="small muted" style="margin-top:6px">${GUIDE_NOTE}</p>` : ''}`;
}

export function openTerm(key) {
  if (!TERMS[key]) return;
  openModal({ title: TERMS[key][0], body: termBody(key) });
}

// どの画面でも、data-term の付いたボタンで説明を開く（1 回だけ登録）
if (typeof document !== 'undefined') {
  document.addEventListener('click', (e) => {
    const b = e.target.closest?.('[data-term]');
    if (b) { e.preventDefault(); e.stopPropagation(); openTerm(b.dataset.term); }
  });
}
